"""Evaluation passes for every finished run, one per registered evaluation pass.

    uv run python scripts/evaluate_grid.py                                   # runs/, every pass, 32 seeds
    uv run python scripts/evaluate_grid.py --root runs/_smoke_post --n-eval-seeds 4 --passes stochastic argmax
    uv run python scripts/evaluate_grid.py --passes all --conditions A-S1-N9 --seeds 0

Passes (``--passes``), each resumable per (run, pass) through ``<run_dir>/eval/manifest.json``:

  stochastic   the primary pass: the selected checkpoint, stochastic action sampling, the 32
               evaluation seeds, ``hamlet.evaluate.evaluate`` unchanged, into
               ``<run_dir>/eval/stochastic/<condition>/<ckpt>/seed<k>_ep0.parquet`` (the layout
               ``scripts/report_pilot.py`` already writes, so the pilot's evaluation is reused).
  argmax       the secondary pass: the same seeds and columns with greedy decoding through
               ``hamlet.evaluate.evaluate(..., mode="argmax")`` (the argmax of the policy's own
               log-probability vector; ``ArgmaxPolicy`` here is the same computation as a wrapper and
               is used only on a tree without that parameter); the Parquet's ``checkpoint`` column
               carries ``<ckpt>_argmax`` so the mode is visible in the data.
  shocks       ``jobs_closed_d4`` (H1c primary) and ``energy_x2_d4`` (the promotion) on every condition,
               each paired with the unshocked stochastic pass on the same seed; the plan names arm A
               (``scope: plan``), the others are run and marked ``scope: superset``. The GREEDY-CLOCK
               reference is shocked too (``<root>/<condition>-<shock>/GREEDY-CLOCK/``).
  init         evaluation-time initial-state dispersion narrow (0.70, 0.80) and wide (0.25, 1.00) on
               A-S0-N<N> and A-S1-N<N> (default (0.50, 1.00) is the stochastic pass itself), condition
               labelled ``<condition>-init_<name>`` in the Parquet.
  swap         on every S1 condition: 4,096 observations sampled uniformly from the seed's own
               stochastic evaluation episodes (regenerated by replaying the same episodes; observations
               are not logged), ``hamlet.metrics.specialisation.swap_test`` for every kind in
               ``SWAP_KINDS`` with a bootstrap over observations, written to
               ``<run_dir>/eval/swap/swap.json``; and the replay counts of the
               ``trait_and_home_shuffle`` DOL null (``hamlet.evaluate.trait_and_home_shuffle_counts``,
               full rollouts, so capped by ``--replay-perm`` and ``--replay-seeds``, both recorded) to
               ``<run_dir>/eval/swap/trait_home_shuffle.npz``.

The per-run manifest records, per pass: mode, seeds, checkpoint path, git describe and commit, the
condition written, scope (plan or superset), file count, and timestamps. Nothing under ``hamlet/``
is edited by this script; every rollout goes through ``hamlet.evaluate.rollout``/``evaluate`` and
every metric through ``hamlet.metrics``.
"""
